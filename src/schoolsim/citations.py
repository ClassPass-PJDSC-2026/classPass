"""Reference list rendering and citation checking (ticket #19).

``references.yaml`` is the single source of truth. This module:

- renders the APA 7th list (markdown and HTML with a hanging indent) in correct order,
- finds author-year citations in text, and
- checks both directions of the acceptance criterion: every citation in the text resolves to
  a reference, and every reference is cited somewhere.

Pure Python; no Streamlit.
"""

from __future__ import annotations

import html
import re
from collections.abc import Iterable, Mapping
from dataclasses import dataclass
from typing import Any

YEAR = r"(?:1[89]\d{2}|20\d{2})[a-z]?"
YEAR_OR_ND = rf"(?:{YEAR}|n\.d\.)"

START_MARK = "<!-- REFERENCES:START (generated by scripts/build_references.py; edit references.yaml instead) -->"
END_MARK = "<!-- REFERENCES:END -->"

REQUIRED_FIELDS = ("author", "short", "apa", "status", "verified_on", "checked_via")
STATUSES = ("verified", "partial")


@dataclass(frozen=True)
class Citation:
    """One author-year citation found in text."""

    author: str  # normalised
    year: str  # "2008", "2020a" or "n.d."
    raw: str
    alternatives: tuple[str, ...] = ()  # other readings of the author (narrative citations with longer names)


def normalise_author(text: str) -> str:
    """Lower-case author text with APA noise removed so spellings compare equal.

    ``"Rudnick & Milton"`` and ``"Rudnick and Milton"`` match; ``"Carrat et al."`` becomes ``"carrat"``;
    leading "The" and quotation marks are dropped (titles used as authors).
    """
    t = text.strip().strip("\"“”'’").strip()
    t = re.sub(r"\bet al\.?", "", t, flags=re.IGNORECASE)
    t = t.replace("&", " and ")
    t = re.sub(r"[\"“”]", "", t)
    t = re.sub(r"\s+", " ", t).strip(" ,.;")
    t = re.sub(r"^the\s+", "", t, flags=re.IGNORECASE)
    return t.lower()


def _entry_year(entry: Mapping[str, Any]) -> str:
    return str(entry["year"]) if entry.get("year") else "n.d."


def author_variants(entry: Mapping[str, Any]) -> set[str]:
    """Normalised author strings that count as a citation of this entry."""
    names = [entry["author"], *(entry.get("aliases") or [])]
    return {normalise_author(n) for n in names}


# --- Finding citations -------------------------------------------------------------------

_PAREN = re.compile(r"\(([^()]+)\)")
_DATE_LIKE = re.compile(r"^(?:jan|feb|mar|apr|may|jun|jul|aug|sep|oct|nov|dec)[a-z]*\.?\s+\d", re.IGNORECASE)
_PIECE = re.compile(rf"^\s*(?P<author>.+?),\s*(?P<years>{YEAR_OR_ND}(?:\s*,\s*{YEAR_OR_ND})*)\s*$")
_NARRATIVE = re.compile(
    r"(?P<prefix>(?:[A-Za-z][\w'’\-.]*\s+){0,4})"
    r"(?P<last>[A-Z][\w'’\-]+(?:\s+(?:&|and)\s+[A-Z][\w'’\-]+|\s+et al\.)?)"
    rf"\s+\((?P<year>{YEAR})\)"
)


def find_citations(text: str) -> list[Citation]:
    """Author-year citations in ``text``: parenthetical and single-surname narrative forms.

    Parenthetical: ``(Carrat et al., 2008)``, ``(Wells, 1955; Riley et al., 1978)``,
    ``(Philippine Statistics Authority, n.d., 2024)``, ``("DepEd Projects," 2026)``.
    Narrative: ``Carrat et al. (2008)``, ``Rudnick & Milton (2003)``.
    """
    found: list[Citation] = []
    for group in _PAREN.findall(text):
        for piece in group.split(";"):
            piece = re.sub(r",([\"”])\s+", r"\1, ", piece)  # APA puts the comma inside the quotes; move it out
            m = _PIECE.match(piece)
            if not m or _DATE_LIKE.match(m.group("author").strip()):
                continue
            author = normalise_author(m.group("author"))
            if not author:
                continue
            for year in re.split(r"\s*,\s*", m.group("years")):
                found.append(Citation(author, year, f"({piece.strip()})"))
    for m in _NARRATIVE.finditer(text):
        last = re.sub(r"\s+et al\.$", "", m.group("last"))
        words = (m.group("prefix") + " " + last).split()
        readings = tuple(normalise_author(" ".join(words[i:])) for i in range(len(words)))
        # Shortest reading first: the author text right before the year.
        readings = tuple(reversed(readings))
        found.append(Citation(readings[0], m.group("year"), m.group(0).strip(), readings[1:]))
    return found


def narrative_forms(entry: Mapping[str, Any]) -> set[str]:
    """Exact narrative strings that cite this entry, e.g. ``"Carrat et al. (2008)"``."""
    year = entry.get("year")
    names = {entry["author"], *(entry.get("aliases") or [])}
    forms = set()
    for name in names:
        if year:
            forms.add(f"{name} ({year})")
            forms.add(f"{name.replace('&', 'and')} ({year})")
        else:
            forms.add(name)
    return forms


def index_citations(refs: Mapping[str, Mapping[str, Any]]) -> dict[tuple[str, str], str]:
    """Map ``(normalised author, year)`` to a reference key."""
    index: dict[tuple[str, str], str] = {}
    for key, entry in refs.items():
        year = _entry_year(entry)
        for author in author_variants(entry):
            index[(author, year)] = key
    return index


def check_text(text: str, refs: Mapping[str, Mapping[str, Any]]) -> tuple[list[str], set[str]]:
    """Check one text.

    Returns:
        ``(unknown, cited)``: ``unknown`` lists citations in the text that match no reference;
        ``cited`` is the set of reference keys the text cites.
    """
    index = index_citations(refs)
    unknown: list[str] = []
    cited: set[str] = set()
    for c in find_citations(text):
        key = next((index[(a, c.year)] for a in (c.author, *c.alternatives) if (a, c.year) in index), None)
        if key:
            cited.add(key)
        else:
            unknown.append(c.raw)
    for key, entry in refs.items():
        year = entry.get("year")
        if year:
            if any(form in text for form in narrative_forms(entry)):
                cited.add(key)
        elif any(form in text for form in narrative_forms(entry)):  # statutes and undated items
            cited.add(key)
    return unknown, cited


# --- Rendering ---------------------------------------------------------------------------

def sort_key(entry: Mapping[str, Any]) -> tuple[str, str]:
    """APA order: by the start of the reference (author or title), ignoring leading articles, then year.

    With the same first author, entries are ordered by the second author's surname (so "&" is ignored)."""
    plain = entry["apa"].replace("*", "").replace("&", "")  # "&" must not decide the order of co-authors
    plain = re.sub(r"\s+", " ", plain)
    plain = re.sub(r"^(the|a|an)\s+", "", plain.strip(), flags=re.IGNORECASE)
    return plain.lower(), _entry_year(entry)


def ordered_entries(refs: Mapping[str, Mapping[str, Any]]) -> list[tuple[str, Mapping[str, Any]]]:
    return sorted(refs.items(), key=lambda kv: sort_key(kv[1]))


def apa_lines(refs: Mapping[str, Mapping[str, Any]]) -> list[str]:
    """The reference list as markdown lines (``*italic*``), alphabetical, one reference per line."""
    return [" ".join(entry["apa"].split()) for _, entry in ordered_entries(refs)]


def render_markdown(refs: Mapping[str, Mapping[str, Any]]) -> str:
    """Markdown version of the list: one paragraph per reference."""
    return "\n\n".join(apa_lines(refs)) + "\n"


_URL = re.compile(r"(https?://[^\s<]+[^\s<.,;)])")


def _to_html(line: str) -> str:
    escaped = html.escape(line, quote=False)
    escaped = re.sub(r"\*([^*]+)\*", r"<i>\1</i>", escaped)
    return _URL.sub(r'<a href="\1">\1</a>', escaped)


def render_html(refs: Mapping[str, Mapping[str, Any]]) -> str:
    """Standalone HTML page with a 0.5 inch hanging indent. Open it, select all, and paste into a
    word processor or design tool to keep the italics and indent."""
    paragraphs = "\n".join(f"<p>{_to_html(line)}</p>" for line in apa_lines(refs))
    return (
        "<!doctype html>\n<html lang=\"en\">\n<head>\n<meta charset=\"utf-8\">\n"
        "<title>References (APA 7th)</title>\n<style>\n"
        "body{font-family:'Times New Roman',Times,serif;font-size:12pt;line-height:2;"
        "max-width:6.5in;margin:1in auto;}\n"
        "h1{font-size:12pt;font-weight:bold;text-align:center;}\n"
        "p{margin:0;padding-left:0.5in;text-indent:-0.5in;}\n"
        "a{color:inherit;text-decoration:none;}\n"
        "</style>\n</head>\n<body>\n<h1>References</h1>\n" + paragraphs + "\n</body>\n</html>\n"
    )


def replace_block(text: str, new_block: str) -> str:
    """Replace the generated reference block between the START and END markers in ``text``."""
    pattern = re.compile(re.escape(START_MARK) + r".*?" + re.escape(END_MARK), re.DOTALL)
    if not pattern.search(text):
        raise ValueError("Reference markers not found")
    return pattern.sub(lambda _: f"{START_MARK}\n\n{new_block.strip()}\n\n{END_MARK}", text)


# --- Validation --------------------------------------------------------------------------

def validate_entries(refs: Mapping[str, Mapping[str, Any]]) -> list[str]:
    """Problems with the reference file itself (empty list when it is sound)."""
    problems: list[str] = []
    seen: dict[tuple[str, str], str] = {}
    for key, entry in refs.items():
        for field in REQUIRED_FIELDS:
            if entry.get(field) in (None, ""):
                problems.append(f"{key}: missing '{field}'")
        if entry.get("status") not in STATUSES:
            problems.append(f"{key}: status must be one of {STATUSES}")
        placeholder = re.search(r"\[(?:date|authors?|year|journal)[^\]]*\]|TODO", entry.get("apa", ""))
        if placeholder and entry.get("status") == "verified":
            problems.append(f"{key}: verified entry still has a placeholder")
        year = entry.get("year")
        if year and str(year) not in entry.get("apa", ""):
            problems.append(f"{key}: year {year} not found in the APA text")
        doi = entry.get("doi")
        if doi and doi not in entry.get("apa", ""):
            problems.append(f"{key}: DOI {doi} not found in the APA text")
        marker = (normalise_author(str(entry.get("author", ""))), _entry_year(entry))
        if marker in seen:
            problems.append(f"{key}: same author and year as {seen[marker]} (add a/b suffixes in APA)")
        seen[marker] = key
    return problems


def unresolved_keys(keys: Iterable[str], refs: Mapping[str, Any], reserved: Iterable[str]) -> list[str]:
    """Source keys that are neither in the reference file nor reserved."""
    allowed = set(refs) | set(reserved)
    return sorted({k for k in keys if k not in allowed})
